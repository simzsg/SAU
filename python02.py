# คำสั่งที่ใช้ในการแสดงผลข้อมูลใดๆ ที่หน้าจอ คือ print( )
# String ข้อความ
print("AAAAA")      # double quote
print('BBBBB')      # single quote
print('''CCCCC''')  # triple quote by single quote
print("""DDDDD""")  # triple quote by double quote

# Number ตัวเลข
print(23456)        # integer
print(158.456878)   # float

# Boolean ตรรกะ (True/False)
print(True)
print(False)

# Expression นิพจน์ คือ อะไรที่มี Process การทำงาน เช่น การคำนวณ, ...
print(10 + 20 + 30)
print(5 * 50)