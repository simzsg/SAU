# ไม่รู้จำนวนซ้ำในการทำซ้ำ


for a in range(10):
    print(f'{a+1} Hello...for loop')

print('-------------------------')

for b in range(3,10):
    print(f'{b} Hello...for loop')

print('-------------------------')

for c in range(2,10,4):
    print(f'{c} Hello...for loop')

