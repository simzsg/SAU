# #โปรแกรมคำนวณอายุ ค่า BMI และแปรผลค่า BMI ที่คำนวณได้ โดยมีการทำงานของโปรแกรมดังนี้
# - ป้อนชื่อ พ.ศ.เกิด น้ำหนักหน่วยเป็นกิโลกรัม และส่วนสูงเป็นเซ็นติเมตร
# - คำนวณอายุจาก พ.ศ. เกิดโดยไปลบกับปี พ.ศ. ปัจจุบัน และแสดงผล
# - คำนวณค่า BMI จากน้ำหนักและส่วนสูงจากสูตร BMI = น้ำหนัก(กิโลกรัม)/ ส่วนสูง(เมตร)2 และแสดงผล กำหนดให้แสดงจำนวนทศนิยม 2 ตำแหน่ง
# - แปลผลจากค่า BMI และแสดงผล โดย
# 	ค่า BMI น้อยกว่า 18.5 ให้แสดงผล น้ำหนักน้อยไป	
# 	ค่า BMI ตั้งแต่ 18.5 ถึง 22.99 ให้แสดงผล น้ำหนักปกติ
# 	ค่า BMI ตั้งแต่ 23 ถึง 24.99 ให้แสดงผล น้ำหนักเกิน (ท้วม)
# 	ค่า BMI ตั้งแต่ 25 ถึง 29.99 ให้แสดงผล น้ำหนักเกิน (อ้วนระยะเริ่มต้น)
# 	ค่า BMI ตั้งแต่ 30 ถึง 39.99 ให้แสดงผล น้ำหนักเกิน (อ้วนมาก)
# 	ค่า BMI ตั้งแต่ 40 ขึ้นไป ให้แสดงผล น้ำหนักเกิน (อ้วนระดับรุนแรงมาก)
 
 
