def headName():
    print('****************************************')
    print('****              BMI Program                ****')
    print('****************************************')


def info_input():
    name = input('ป้อนชื่อ : ')
    year = int(input('ป้อนปี พ.ศ. เกิด : '))
    weight = float(input('ป้อนน้ำหนัก : '))
    height = float(input('ป้อนส่วนสูง : '))
    return name, year, weight, height

def bmi(weight, height):
    bmi = weight / (height / 100) ** 2
    return bmi


def notice(bmi , name, year, age, weight, height):
    print(f'คุณ{name} เกิดปี {year} อายุ {age} ปี')
    print(f'น้ำหนัก {weight} กิโลกรัม ส่วนสูง {height} เซนติเมตร')
    print(f'ค่า BMI ที่คำนวณได้ คือ {bmi:.2f}')


    if bmi < 18.5:
        print('น้ำหนักน้อยไป')
    elif 18.5 <= bmi < 22.99:
        print('น้ำหนักปกติ')
    elif 23 <= bmi < 24.99:
        print('น้ำหนักเกิน (ท้วม)')
    elif 25 <= bmi < 29.99:
        print('น้ำหนักเกิน (อ้วนระยะเริ่มต้น)')
    elif 30 <= bmi < 39.99:
        print('น้ำหนักเกิน (อ้วนมาก)')
    else:
        print('น้ำหนักเกิน (อ้วนระดับรุนแรงมาก)')

    

def age (year):
    age = 2568 - year
    return age

headName()
name, year, weight, height = info_input()
